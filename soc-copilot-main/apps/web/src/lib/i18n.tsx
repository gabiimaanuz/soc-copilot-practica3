export type TranslationKey = keyof typeof translations.es;

// ─── Context ──────────────────────────────────────────────────────────────────

interface I18nState {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TranslationKey) => string;
}

const I18nCtx = createContext<I18nState | null>(null);

const STORAGE_KEY = "soc:locale";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("es");

  useEffect(() => {
    let saved: Locale | null = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
    } catch {
      /* storage disabled */
    }
    if (saved && saved in translations) {
      setLocaleState(saved);
      return;
    }
    // First visit: auto-detect from the browser (Práctica 2 · ES/EN).
    const nav = (navigator.languages?.[0] ?? navigator.language ?? "es")
      .slice(0, 2)
      .toLowerCase();
    const detected = (nav in translations ? nav : "es") as Locale;
    setLocaleState(detected);
    try {
      localStorage.setItem(STORAGE_KEY, detected);
    } catch {
      /* storage disabled */
    }
  }, []);

  function setLocale(l: Locale) {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage disabled */
    }
  }

  const t = (key: TranslationKey): string =>
    (translations[locale] as Record<string, string>)[key] ??
    (translations.es as Record<string, string>)[key] ??
    key;

  return (
    <I18nCtx.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nCtx.Provider>
  );
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
